-- ── 1) تصحيح التهجئة: «خانيونس» ← «خان يونس» ──────────────────────────
--  خطأ إملائي صرف. يشمل كل الأدوار لا الدعاة وحدهم، حتى لا يبقى مشرف
--  مربوطاً بالتهجئة الخاطئة فينكسر نطاقه.

UPDATE `users`
SET `governorate` = 'خان يونس'
WHERE `governorate` = 'خانيونس';


-- ── 2) «الجنوب» ← «خان يونس» ──────────────────────────────────────────
--  قرار إداري: «الجنوب» كانت خطأ إدخال لا محافظة قائمة.
--
--  ⚠ مقصورة على الدعاة عمداً: مسمّى علاء العرقان الإداري يذكر «المحافظة
--  الجنوبية»، لكن محافظته المسجّلة «خان يونس» أصلاً فلا يمسّه هذا السطر.

UPDATE `users`
SET `governorate` = 'خان يونس'
WHERE `governorate` = 'الجنوب'
  AND `role` = 'preacher';


